(function navToggle() {
  const btn = document.getElementById('hamburgerBtn');
  const nav = document.getElementById('mainNav');
  if (!btn || !nav) return;

  function closeMenu() {
    nav.classList.remove('is-open');
    btn.classList.remove('is-open');
    btn.setAttribute('aria-expanded', 'false');
  }

  btn.addEventListener('click', () => {
    const isOpen = nav.classList.toggle('is-open');
    btn.classList.toggle('is-open', isOpen);
    btn.setAttribute('aria-expanded', String(isOpen));
  });

  nav.querySelectorAll('a').forEach((link) => link.addEventListener('click', closeMenu));
})();

// ===================== Booking modal =====================
(function bookingModal() {
  const overlay = document.getElementById('modalOverlay');
  const closeBtn = document.getElementById('modalClose');
  const form = document.getElementById('bookingForm');
  const tourNameEl = document.getElementById('modalTourName');
  const tourPriceEl = document.getElementById('modalTourPrice');
  const errorEl = document.getElementById('formError');
  const successEl = document.getElementById('formSuccess');
  const submitBtn = document.getElementById('submitBtn');
  const nameInput = document.getElementById('bookingName');
  const phoneInput = document.getElementById('bookingPhone');
  const messageInput = document.getElementById('bookingMessage');

  const PHONE_RE = /^\+?[0-9()\-\s]{7,20}$/;
  let currentTour = '';
  let currentPrice = '';

  function resetForm() {
    form.reset();
    form.classList.remove('is-hidden');
    errorEl.classList.remove('is-visible');
    errorEl.textContent = '';
    successEl.classList.remove('is-visible');
    submitBtn.disabled = false;
    submitBtn.querySelector('span').textContent = t('modal.send');
  }

  const modalTitleEl = document.getElementById('modalTitle');
  const CONSULTATION_TOUR = 'Free consultation';

  function isConsultation() {
    return currentTour === CONSULTATION_TOUR;
  }

  function openModal(tourName, price) {
    currentTour = tourName;
    currentPrice = price || '';
    modalTitleEl.textContent = isConsultation() ? t('modal.titleConsultation') : t('modal.title');
    tourNameEl.textContent = isConsultation() ? t('hero.cta2') : tourName;
    tourPriceEl.textContent = currentPrice || '—';
    tourPriceEl.style.display = currentPrice ? '' : 'none';
    resetForm();
    overlay.classList.add('is-open');
    document.body.style.overflow = 'hidden';
    nameInput.focus();
  }

  function closeModal() {
    overlay.classList.remove('is-open');
    document.body.style.overflow = '';
  }

  document.querySelectorAll('.book-btn').forEach((btn) => {
    btn.addEventListener('click', () => {
      openModal(btn.getAttribute('data-tour'), btn.getAttribute('data-price'));
    });
  });

  document.addEventListener('languagechange', () => {
    if (!overlay.classList.contains('is-open')) return;
    modalTitleEl.textContent = isConsultation() ? t('modal.titleConsultation') : t('modal.title');
    tourNameEl.textContent = isConsultation() ? t('hero.cta2') : currentTour;
  });

  closeBtn.addEventListener('click', closeModal);
  overlay.addEventListener('click', (e) => {
    if (e.target === overlay) closeModal();
  });
  document.addEventListener('keydown', (e) => {
    if (e.key === 'Escape' && overlay.classList.contains('is-open')) closeModal();
  });

  function showError(message) {
    errorEl.textContent = message;
    errorEl.classList.add('is-visible');
  }

  form.addEventListener('submit', async (e) => {
    e.preventDefault();
    errorEl.classList.remove('is-visible');

    const name = nameInput.value.trim();
    const phone = phoneInput.value.trim();
    const message = messageInput.value.trim();

    if (name.length < 2) {
      showError(t('modal.errNameRequired'));
      nameInput.focus();
      return;
    }
    if (!PHONE_RE.test(phone)) {
      showError(t('modal.errPhoneInvalid'));
      phoneInput.focus();
      return;
    }

    submitBtn.disabled = true;
    submitBtn.querySelector('span').textContent = t('modal.sending');

    try {
      const response = await fetch('/api/order', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          tour: currentTour,
          price: currentPrice,
          name,
          phone,
          message,
          lang: currentLang,
        }),
      });

      const data = await response.json();

      if (response.ok && data.success) {
        form.classList.add('is-hidden');
        successEl.classList.add('is-visible');
      } else {
        showError(data.error || t('modal.errServer'));
        submitBtn.disabled = false;
        submitBtn.querySelector('span').textContent = t('modal.send');
      }
    } catch (err) {
      showError(t('modal.errNetwork'));
      submitBtn.disabled = false;
      submitBtn.querySelector('span').textContent = t('modal.send');
    }
  });
})();


(function heroSlider() {
  const slides = document.querySelectorAll('.hero-slide');
  const dots = document.querySelectorAll('.hero-dot');
  if (!slides.length) return;

  let index = 0;
  const prefersReducedMotion = window.matchMedia('(prefers-reduced-motion: reduce)').matches;

  function goTo(newIndex) {
    slides[index].classList.remove('is-active');
    dots[index] && dots[index].classList.remove('is-active');
    index = newIndex;
    slides[index].classList.add('is-active');
    dots[index] && dots[index].classList.add('is-active');
  }

  dots.forEach((dot) => {
    dot.addEventListener('click', () => goTo(Number(dot.getAttribute('data-index'))));
  });

  if (!prefersReducedMotion) {
    setInterval(() => goTo((index + 1) % slides.length), 5500);
  }
})();


const SUPPORTED_LANGS = ['uz', 'ru', 'en'];
const LANG_STORAGE_KEY = 'ipakyoli_lang';
let currentLang = localStorage.getItem(LANG_STORAGE_KEY) || 'uz';
if (!SUPPORTED_LANGS.includes(currentLang)) currentLang = 'uz';

// Translation helper used both by applyLanguage() and inline JS strings (e.g. form errors).
function t(key) {
  return (dict[currentLang] && dict[currentLang][key]) || dict.en[key] || key;
}

// Applies the active language to every [data-i18n] / [data-i18n-ph] element on the page.
function applyLanguage(lang) {
  currentLang = SUPPORTED_LANGS.includes(lang) ? lang : 'uz';
  document.documentElement.lang = currentLang;
  localStorage.setItem(LANG_STORAGE_KEY, currentLang);

  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    if (dict[currentLang][key] !== undefined) {
      el.textContent = dict[currentLang][key];
    }
  });

  if (dict[currentLang]['meta.title']) {
    document.title = dict[currentLang]['meta.title'];
  }
  const metaDescriptionEl = document.querySelector('meta[name="description"]');
  if (metaDescriptionEl && dict[currentLang]['meta.description']) {
    metaDescriptionEl.setAttribute('content', dict[currentLang]['meta.description']);
  }

  document.querySelectorAll('[data-i18n-ph]').forEach((el) => {
    const key = el.getAttribute('data-i18n-ph');
    if (dict[currentLang][key] !== undefined) {
      el.setAttribute('placeholder', dict[currentLang][key]);
    }
  });

  document.querySelectorAll('.lang-btn').forEach((btn) => {
    btn.classList.toggle('is-active', btn.getAttribute('data-lang') === currentLang);
  });

  document.dispatchEvent(new CustomEvent('languagechange'));
}

document.querySelectorAll('.lang-btn').forEach((btn) => {
  btn.addEventListener('click', () => applyLanguage(btn.getAttribute('data-lang')));
});

applyLanguage(currentLang);

